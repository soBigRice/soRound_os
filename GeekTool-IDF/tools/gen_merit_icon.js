// Render the approved SVG at its native size, then use LVGL's own lossless converter.
// Run with Node + sharp, Python + pypng/lz4: node tools/gen_merit_icon.js [python]
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { execFileSync } = require('node:child_process');
const sharp = require('sharp');

const root = path.resolve(__dirname, '..');
const artwork = path.join(root, 'artwork/merit/icon-design-20261013');
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'merit-icon-'));

(async () => {
    try {
        const png = path.join(artwork, 'merit-icon-v2.png');
        await sharp(path.join(artwork, 'merit-icon-v2.svg')).png().toFile(png);
        execFileSync(process.argv[2] || 'python3', [
            path.join(root, 'managed_components/lvgl__lvgl/scripts/LVGLImage.py'),
            '--ofmt', 'C', '--cf', 'A8', '--compress', 'RLE', '--name', 'merit_icon',
            '--output', work, png,
        ], { stdio: 'inherit' });
        const generated = fs.readFileSync(path.join(work, 'merit_icon.c'), 'utf8');
        const declaration = generated.slice(generated.indexOf('#ifndef LV_ATTRIBUTE_MEM_ALIGN'))
            .replace('const lv_image_dsc_t merit_icon =', 'static const lv_image_dsc_t merit_icon =');
        fs.writeFileSync(path.join(root, 'main/merit_icon.inc'),
            '// Generated by tools/gen_merit_icon.js from the approved merit-icon-v2.svg.\n' + declaration.trimEnd() + '\n');
    } finally {
        fs.rmSync(work, { recursive: true, force: true });
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
