#!/usr/bin/env python3
"""Encode approved independent imagegen assets as RGB565 LVGL images.
将独立生成素材转换为 RGB565；不把界面稿烘焙进固件。
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "artwork/companion-apps"


def encode(name: str, size: tuple[int, int], threshold: int) -> None:
    source = Image.open(ART / f"{name}-source.png").convert("RGB")
    # Trim only the generated black backdrop; retain a two-pixel safety margin.
    # 仅去掉生成图的纯黑外边；四边保留安全余量，不改变有效内容比例。
    mask = source.convert("L").point(lambda v: 255 if v > threshold else 0)
    bounds = mask.getbbox()
    if bounds is None:
        raise ValueError(f"empty asset: {name}")
    x0, y0, x1, y1 = bounds
    source = source.crop((max(0, x0 - 2), max(0, y0 - 2), min(source.width, x1 + 2), min(source.height, y1 + 2)))
    source.thumbnail(size, Image.Resampling.LANCZOS)
    target = Image.new("RGB", size)
    target.paste(source, ((size[0] - source.width) // 2, (size[1] - source.height) // 2))
    alpha = bytearray(255 if max(pixel) > 8 else 0 for pixel in target.get_flattened_data())
    preview = target.convert("RGBA"); preview.putalpha(Image.frombytes("L", size, bytes(alpha)))
    preview.save(ART / f"{name}-device.png")
    data = bytearray()
    for r, g, b in target.get_flattened_data():
        value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data.extend((value & 255, value >> 8))
    # LVGL RGB565A8 stores the alpha plane after all RGB565 rows.
    # LVGL 的独立 A8 平面紧跟全部 RGB565 行；黑色外底透明以便昼夜着色与旋转。
    data.extend(alpha)
    symbol = name.upper()
    lines = [f"// Generated by tools/gen_companion_artwork.py; RGB565A8 LE, {size[0]}x{size[1]}.",
             f"#define {symbol}_ART_WIDTH {size[0]}", f"#define {symbol}_ART_HEIGHT {size[1]}",
             f"_Alignas(4) static const uint8_t {name}_pixels[] = {{"]
    lines.extend("    " + ",".join(f"0x{n:02x}" for n in data[i:i + 24]) + "," for i in range(0, len(data), 24))
    lines.extend(["};", f"static const lv_image_dsc_t {name}_image = {{",
                  f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .w = {size[0]}, .h = {size[1]}, .stride = {size[0] * 2}}},",
                  f"    .data_size = sizeof {name}_pixels, .data = {name}_pixels", "};", ""])
    (ROOT / f"main/{name}_artwork.inc").write_text("\n".join(lines))
    print(f"{name}: {len(data):,} bytes RGB565A8, source crop {bounds}, device {size}")


if __name__ == "__main__":
    encode("garden", (334, 238), 15)
    encode("focus", (256, 256), 12)
