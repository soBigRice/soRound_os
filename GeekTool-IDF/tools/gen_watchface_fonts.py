#!/usr/bin/env python3
"""Rasterize pinned Barlow subsets; preserve 4bpp pixels with LVGL lossless RLE."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import json
import subprocess

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "artwork/watchfaces/fonts"
OUTPUT = ROOT / "main/font_watchface.c"
SUBSETS = [(s, "regular", ''.join(chr(c) for c in range(32, 127)) + '°')
           for s in (7, 9, 14, 18)]
SUBSETS += [(s, "black", "0123456789:-°") for s in (26, 36, 52, 56, 72, 82, 104, 112, 164)]
SUBSETS = [(size,weight,subset,f'font_wf_{size}') for size,weight,subset in SUBSETS]
# Approved clocks use separate weights: light ring digits, medium horizontal
# clocks/temperatures, and oversized black stacked digits. Export only needed pairs.
SUBSETS += [(size,weight,"0123456789:-°",f'font_wf_{weight}_{size}')
            for weight,sizes in (('regular',(48,96)),('black',(94,188)),
                                 ('semibold',(14,26,28,52,56,104,112))) for size in sizes]

def generate(subsets=SUBSETS, output=OUTPUT):
    source = ['// Generated by tools/gen_watchface_fonts.py; lossless 4bpp Barlow subsets.\n'
              '// Copyright 2017 The Barlow Project Authors; SIL OFL 1.1.\n'
              '// License and pinned source: artwork/watchfaces/fonts/.\n#include "watchface_ui.h"\n'
              'LV_FONT_DECLARE(font_cn16);\n'
              'static const char font_license[]='+json.dumps((FONTS/'OFL.txt').read_text())+';\n']
    for size, weight, subset, symbol in subsets:
        filename={'regular':'Regular','black':'Black','semibold':'SemiBold'}[weight]
        font = ImageFont.truetype(str(FONTS / f"Barlow-{filename}.ttf"), size)
        codes = sorted(set(map(ord, subset)))
        boxes = [font.getbbox(chr(code), anchor="ls") for code in codes]
        top = min(b[1] for b in boxes); bottom = max(b[3] for b in boxes)
        bitmap = []; records = []; filtered_glyphs = []; raw_glyphs = []
        for code, (x0, y0, x1, y1) in zip(codes, boxes):
            width, height = x1-x0, y1-y0
            image = Image.new('L', (max(1,width), max(1,height)))
            ImageDraw.Draw(image).text((-x0, -y0), chr(code), font=font, fill=255, anchor="ls")
            # Crop true ink bounds; advance remains the original proportional font metric.
            bounds = image.getbbox()
            if bounds:
                ink = image.crop(bounds); width, height = ink.size
                x = x0 + bounds[0]; y = -(y0 + bounds[3])
                values = [p >> 4 for p in ink.tobytes()]
                raw_glyphs.append([(values[i] << 4) | (values[i+1] if i+1<len(values) else 0)
                                   for i in range(0,len(values),2)])
                # LVGL's built-in XOR prefilter preserves every original 4bpp value.
                filtered_glyphs.append([value ^ (values[i-width] if i >= width else 0)
                                        for i,value in enumerate(values)])
            else:
                width=height=x=y=0
                filtered_glyphs.append([])
                raw_glyphs.append([])
            records.append((round(font.getlength(chr(code))*16),width,height,x,y))
        encoded = json.loads(subprocess.run(
            ['node', str(ROOT/'tools/compress_watchface_fonts.js')],
            input=json.dumps(filtered_glyphs), text=True, capture_output=True, check=True).stdout)
        raw_bytes = sum(map(len,raw_glyphs))
        compressed = sum(map(len,encoded)) < raw_bytes
        payloads = encoded if compressed else raw_glyphs
        glyphs = ['{0,0,0,0,0,0}']
        for record,payload in zip(records,payloads,strict=True):
            glyphs.append('{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}' %
                          (len(bitmap),*record))
            bitmap.extend(payload)
        key = f'{weight}_{size}'
        source.append(f'static const uint8_t bitmap_{key}[]={{\n' +
                      '\n'.join(','.join(f'0x{p:02x}' for p in bitmap[i:i+24])+',' for i in range(0,len(bitmap),24)) + '\n};\n')
        source.append(f'static const lv_font_fmt_txt_glyph_dsc_t glyphs_{key}[]={{'+',\n'.join(glyphs)+'};\n')
        source.append(f'static const uint16_t unicode_{key}[]={{'+','.join(str(c-codes[0]) for c in codes)+'};\n')
        source.append(f'static const lv_font_fmt_txt_cmap_t cmap_{key}[]={{'
                      f'{{.range_start={codes[0]},.range_length={codes[-1]-codes[0]+1},.glyph_id_start=1,'
                      f'.unicode_list=unicode_{key},.list_length={len(codes)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}}};\n')
        source.append(f'static const lv_font_fmt_txt_dsc_t dsc_{key}={{.glyph_bitmap=bitmap_{key},'
                      f'.glyph_dsc=glyphs_{key},.cmaps=cmap_{key},.cmap_num=1,.bpp=4,'
                      f'.bitmap_format={"LV_FONT_FMT_TXT_COMPRESSED" if compressed else "LV_FONT_FMT_TXT_PLAIN"}}};\n')
        fallback=',.fallback=&font_cn16' if weight=='regular' else ''
        source.append(f'const lv_font_t {symbol}={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,'
                      f'.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={bottom-top},'
                      f'.base_line={bottom},.dsc=&dsc_{key}{fallback},.user_data=(void *)font_license}};\n')
        print(f'{weight} {size}px: {len(codes)} glyphs, {raw_bytes} -> {len(bitmap)} bytes (lossless)')
    output.write_text(''.join(source))

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hands', action='store_true', help='Only generate the small analog numeral subsets')
    parser.add_argument('--studio', action='store_true', help='Only generate the approved STUDIO numeral pairs')
    parser.add_argument('--typography', action='store_true', help='Generate the oversized typography pairs without changing existing fonts')
    args = parser.parse_args()
    if args.studio:
        # 原稿字号及半尺寸预览逐一保留，旧字库不重栅格化。 / Preserve each approved size and its half-size preview without touching legacy fonts.
        sizes_by_weight = {'regular': (8,9,10,11,12,13,14,15,30,72,86,87,88,91,96,99),
                           'semibold': (12,13,14,94,96,144,146)}
        studio = [(size, weight, (''.join(chr(c) for c in range(32,127))+'·') if size<=18 else '0123456789:',
                   f'font_studio_{weight}_{size}')
                  for weight, originals in sizes_by_weight.items()
                  for size in sorted(set(originals) | {(size+1)//2 for size in originals})]
        generate(studio, ROOT / 'main/font_watchface_studio.c')
        declarations = '// 原稿字体及半尺寸预览；由同目录生成器维护。 / Approved fonts and half-size previews; generated together.\n#pragma once\n#include "lvgl.h"\n'
        declarations += ''.join(f'LV_FONT_DECLARE({symbol});\n' for _,_,_,symbol in studio)
        declarations += 'static inline const lv_font_t *wfs_studio_font(int size,bool preview,bool heavy){\nint pixels=preview?(size+1)/2:size;\nif(heavy){switch(pixels){\n'
        for weight in ('semibold','regular'):
            declarations += ''.join(f'case {size}:return &{symbol};\n' for size,w,_,symbol in studio if w==weight)
            declarations += '} } switch(pixels){\n' if weight=='semibold' else '}return &font_studio_regular_14;\n}\n'
        (ROOT / 'main/watchface_studio_fonts.h').write_text(declarations)
    elif args.typography:
        # 大字系列独立生成，既有字库逐字节保持；每个正屏字号配套半尺寸预览。
        # Generate oversized pairs separately, preserving every existing font and matching each preview size.
        sizes = {'regular': (161,166,176), 'semibold': (166,215), 'black': (200,202,220)}
        fonts = [(size,weight,'0123456789:',f'font_type_{weight}_{size}')
                 for weight, originals in sizes.items()
                 for size in sorted(set(originals) | {(size+1)//2 for size in originals})]
        generate(fonts, ROOT / 'main/font_watchface_type.c')
        header = '// 极简大字独立字库及半尺寸预览。 / Separate oversized fonts and paired previews.\n#pragma once\n#include "lvgl.h"\n'
        header += 'typedef enum {WFT_REGULAR, WFT_MEDIUM, WFT_BLACK} wft_weight_t;\n'
        header += ''.join(f'LV_FONT_DECLARE({symbol});\n' for _,_,_,symbol in fonts)
        header += 'static inline const lv_font_t *wft_font(int size,bool preview,wft_weight_t weight){\nint pixels=preview?(size+1)/2:size;\nswitch(weight){\n'
        for weight, tag in [('regular','WFT_REGULAR'),('semibold','WFT_MEDIUM'),('black','WFT_BLACK')]:
            header += f'case {tag}:switch(pixels){{\n'
            header += ''.join(f'case {size}:return &{symbol};\n' for size,w,_,symbol in fonts if w==weight)
            header += '}break;\n'
        header += '}return NULL;\n}\n'
        (ROOT / 'main/watchface_type_fonts.h').write_text(header)
    elif args.hands:
        generate([(size, weight, '0123456789', f'font_hand_{weight}_{size}')
                  for weight, sizes in [('regular', (12,24)), ('semibold', (16,32))] for size in sizes],
                 ROOT / 'main/font_watchface_hands.c')
    else:
        generate()
