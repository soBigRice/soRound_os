// 从已选定SVG生成A8/RLE资源；不重新拟合轮廓。 / Convert approved SVGs to A8/RLE without refitting.
// Node + sharp; Python + pypng/lz4: node tools/gen_launcher_icons.cjs [python]
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const {execFileSync} = require('node:child_process');
const sharp = require('sharp');

const root = path.resolve(__dirname,'..');
const selected = path.join(root,'artwork/launcher/icon-design-20261019/selected');
const manifest = JSON.parse(fs.readFileSync(path.join(selected,'manifest.json'),'utf8'));
const work = fs.mkdtempSync(path.join(os.tmpdir(),'launcher-icon-convert-'));
const python = process.argv[2] || 'python3';

async function convert(alpha,name) {
    const png = path.join(work,name+'.png');
    const rgba = Buffer.alloc(alpha.length*4,255);
    alpha.forEach((value,i)=>{rgba[i*4+3]=value});
    await sharp(rgba,{raw:{width:manifest.size,height:manifest.size,channels:4}}).png().toFile(png);
    execFileSync(python,[path.join(root,'managed_components/lvgl__lvgl/scripts/LVGLImage.py'),
        '--ofmt','C','--cf','A8','--compress','RLE','--name',name,'--output',work,png],{stdio:'pipe'});
    const c = fs.readFileSync(path.join(work,name+'.c'),'utf8');
    return c.slice(c.indexOf('#ifndef LV_ATTRIBUTE_MEM_ALIGN'))
        .replace(`const lv_image_dsc_t ${name} =`,`static const lv_image_dsc_t ${name} =`);
}

(async()=>{
    try {
        const enumText = fs.readFileSync(path.join(root,'main/launcher_icons.h'),'utf8');
        const kinds = enumText.slice(enumText.indexOf('typedef enum'),enumText.indexOf('LAUNCHER_ICON_COUNT'))
            .match(/LAUNCHER_[A-Z_]+/g);
        if(manifest.size!==148 || JSON.stringify(kinds)!==JSON.stringify(manifest.icons.map(icon=>icon.kind)))
            throw new Error('Approved icon manifest must match the launcher enum exactly');
        let output='// Generated by tools/gen_launcher_icons.cjs; approved direction A.\n';
        output+='// 白色主体与红色细节共用既有A8解码器。 / White ink and red accents use the existing A8 decoder.\n';
        const entries=[];
        for(const icon of manifest.icons) {
            const svg=fs.readFileSync(path.join(selected,icon.id+'.svg'));
            if(crypto.createHash('sha256').update(svg).digest('hex')!==icon.sha256)
                throw new Error('Approved source changed: '+icon.id);
            const rgba=await sharp(svg).ensureAlpha().raw().toBuffer({resolveWithObject:true});
            if(rgba.info.width!==148 || rgba.info.height!==148 || rgba.info.channels!==4)
                throw new Error('Unexpected icon canvas: '+icon.id);
            const white=Buffer.alloc(148*148),red=Buffer.alloc(148*148);
            for(let i=0;i<white.length;i++) {
                const [r,g,b,a]=rgba.data.subarray(i*4,i*4+4);
                const redAlpha=Math.max(0,Math.min(1,(r-g)/169*a/255));
                const whitePremultiplied=Math.max(0,Math.min(1,(g*a/255-40*redAlpha)/245));
                // 先白后红按source-over合成；反解底层alpha避免彩色接缝变暗。
                // Solve the underlying alpha for white-then-red source-over to preserve colored edges.
                red[i]=Math.round(redAlpha*255);
                white[i]=redAlpha>=1 ? 0 : Math.round(Math.min(1,whitePremultiplied/(1-redAlpha))*255);
                const reconstructed=[245*whitePremultiplied+209*redAlpha,245*whitePremultiplied+40*redAlpha,242*whitePremultiplied+58*redAlpha];
                if(Math.max(...[r,g,b].map((value,c)=>Math.abs(value*a/255-reconstructed[c])))>2)
                    throw new Error('Unexpected color outside the approved ink palette: '+icon.id);
            }
            const base='launcher_'+icon.id;
            output+=await convert(white,base+'_white');
            const accent=red.some(value=>value>0);
            if(accent)output+=await convert(red,base+'_red');
            entries.push(`    [${icon.kind}] = { &${base}_white, ${accent?'&'+base+'_red':'NULL'} },`);
        }
        output+='\nstatic const struct { const lv_image_dsc_t *white, *red; } launcher_artwork[] = {\n'+entries.join('\n')+'\n};\n';
        output+=`_Static_assert(LAUNCHER_ICON_COUNT == ${manifest.icons.length}, "Regenerate artwork when the launcher registry changes");\n`;
        fs.writeFileSync(path.join(root,'main/launcher_artwork.inc'),output);
        console.log('Generated '+manifest.icons.length+' approved icons as A8/RLE alpha planes.');
    } finally {
        fs.rmSync(work,{recursive:true,force:true});
    }
})().catch(error=>{console.error(error.message);if(error.stderr)console.error(error.stderr.toString());process.exitCode=1});
