#!/usr/bin/env python3
"""把随仓库保留的 Lucide SVG 转为局部 A8 图标。Render vendored Lucide SVG to A8."""
from pathlib import Path
import subprocess
import tempfile
from PIL import Image

root = Path(__file__).resolve().parents[1]
output = ['// Generated by tools/gen_remote_icons.py; Lucide 0.468.0, ISC.\n']
for filename, symbol in [('mouse', 'remote_mouse_icon'), ('lock-keyhole', 'remote_lock_icon')]:
    source = root / 'artwork' / 'remote' / 'icons' / f'{filename}.svg'
    with tempfile.TemporaryDirectory(prefix='soround-icon-') as tmp:
        svg, png = Path(tmp) / 'icon.svg', Path(tmp) / 'icon.png'
        svg.write_text(source.read_text().replace('currentColor', '#ffffff'))
        subprocess.run(['rsvg-convert', '-w', '30', '-h', '30', '-o', str(png), str(svg)], check=True)
        alpha = Image.open(png).convert('RGBA').getchannel('A').tobytes()
    output.append(f'static const uint8_t {symbol}_data[] = {{\n')
    output.extend(','.join(f'0x{v:02x}' for v in alpha[i:i+24])+',\n' for i in range(0, len(alpha), 24))
    output.append(f'''}};
static const lv_image_dsc_t {symbol} = {{
    .header = {{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_A8,.w=30,.h=30,.stride=30}},
    .data={symbol}_data,.data_size=sizeof {symbol}_data
}};
''')
(root / 'main' / 'remote_icons.inc').write_text(''.join(output))

output = ['// Generated by tools/gen_remote_icons.py; Phosphor 2.1.1, MIT, direction A.\n']
for filename in ['sprout', 'disc-3', 'mic']:
    symbol = 'companion_' + filename.replace('-', '_')
    with tempfile.TemporaryDirectory(prefix='soround-icon-') as tmp:
        svg, png = Path(tmp) / 'icon.svg', Path(tmp) / 'icon.png'
        # 使用与A套相同的已校准画布，不以SVG容器宽度替代可见边界。
        # Use the aligned A canvas rather than treating the SVG viewport as its visible bounds.
        svg.write_text((root / 'artwork/launcher/icon-design-20261019/additional' / f'{filename}.svg').read_text())
        subprocess.run(['rsvg-convert', '-w', '148', '-h', '148', '-o', str(png), str(svg)], check=True)
        alpha = Image.open(png).convert('RGBA').getchannel('A').tobytes()
    output.append(f'static const uint8_t {symbol}_data[] = {{\n')
    output.extend(','.join(f'0x{v:02x}' for v in alpha[i:i+24])+',\n' for i in range(0, len(alpha), 24))
    output.append(f'''}};
static const lv_image_dsc_t {symbol} = {{
    .header = {{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_A8,.w=148,.h=148,.stride=148}},
    .data={symbol}_data,.data_size=sizeof {symbol}_data
}};
''')
(root / 'main' / 'companion_icons.inc').write_text(''.join(output))
